"""Turn a Claude Design canvas (project/ folder of .dc.html artboards) into a
HyperFrames carousel composition, so render_carousel.py can export PNGs locally.

Usage:
  uv run dc_to_carousel.py <claude-design>/project --out projects/<slug>/carousel/render [--preset ig-carousel]

- Slides follow canvas.json `order`; slide i is visible during [i-1, i) s.
- `{{prop}}` holes are filled with each artboard's data-props defaults.
- Images: an <img data-asset="flag-br.svg" src="/_blob/..."> (Claude Design upload) is
  rewritten to src="assets/icons/flag-br.svg"; keep the same file in <out>/assets/icons/.
- Fonts: every .ttf/.otf in <out>/assets/fonts becomes an @font-face; the family
  is the file stem before "-" split on CamelCase (InstrumentSerif-Italic.ttf ->
  "Instrument Serif", italic). Put the brand fonts there before running.
"""
import argparse
import html
import json
import re
import sys
from pathlib import Path

PRESETS_FILE = Path(__file__).resolve().parent.parent / "assets" / "platforms.json"


def font_faces(font_dir: Path) -> str:
    rules = []
    for f in sorted(list(font_dir.glob("*.ttf")) + list(font_dir.glob("*.otf"))):
        stem, _, style = f.stem.partition("-")
        family = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", stem)
        italic = "italic" if "italic" in style.lower() else "normal"
        rules.append(f'@font-face {{ font-family: "{family}"; src: url("assets/fonts/{f.name}"); font-weight: 100 900; font-style: {italic}; }}')
    return "\n      ".join(rules)


def artboard_body(src: str) -> str:
    """Inner markup of <x-dc> without <helmet>, holes filled from data-props defaults."""
    m = re.search(r"<x-dc>(.*?)</x-dc>", src, re.S)
    if not m:
        raise ValueError("no <x-dc> block")
    body = re.sub(r"<helmet>.*?</helmet>", "", m.group(1), flags=re.S).strip()
    props_m = re.search(r"data-props='(.*?)'", src, re.S)
    props = json.loads(html.unescape(props_m.group(1))) if props_m else {}
    defaults = {k: v.get("default") for k, v in props.items() if isinstance(v, dict) and "default" in v}

    def fill(hole: re.Match) -> str:
        key = hole.group(1).strip()
        if key not in defaults:
            raise KeyError(f"hole {{{{{key}}}}} has no data-props default")
        return str(defaults[key])

    body = re.sub(r"\{\{\s*([\w.]+)\s*\}\}", fill, body)
    return re.sub(r"<img\b[^>]*>", local_asset, body)


def local_asset(tag: re.Match) -> str:
    """Point Claude Design uploads (/_blob/<id>) at the local copy named in data-asset."""
    t = tag.group(0)
    m = re.search(r'data-asset="([^"]+)"', t)
    if not m:
        return t
    return re.sub(r'src="[^"]*"', f'src="assets/icons/{m.group(1)}"', t)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project", type=Path, help="folder holding canvas.json and the .dc.html artboards")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--preset", default="ig-carousel")
    args = ap.parse_args()

    preset = json.loads(PRESETS_FILE.read_text(encoding="utf-8"))["presets"][args.preset]
    w, h = preset["width"], preset["height"]
    canvas = json.loads((args.project / "canvas.json").read_text(encoding="utf-8"))
    order = canvas["order"]

    sections = []
    for i, name in enumerate(order):
        body = artboard_body((args.project / name).read_text(encoding="utf-8"))
        sections.append(
            f'      <section id="slide{i + 1}" class="clip" data-start="{i}" data-duration="1" data-track-index="1">\n'
            f"{body}\n      </section>"
        )

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "assets" / "fonts").mkdir(parents=True, exist_ok=True)
    page = f"""<!doctype html>
<html lang="pt-BR">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={w}, height={h}" />
    <title>{html.escape(canvas.get("title", "Carousel"))}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      {font_faces(args.out / "assets" / "fonts")}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: {w}px; height: {h}px; overflow: hidden; background: #000; }}
      #root {{ position: relative; width: {w}px; height: {h}px; overflow: hidden; }}
      .clip {{ position: absolute; inset: 0; }}
    </style>
  </head>
  <body>
    <!-- generated by dc_to_carousel.py from {args.project.name}/canvas.json; edit the .dc.html sources, not this file -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{len(order)}" data-width="{w}" data-height="{h}" data-layout-allow-overflow>
{chr(10).join(sections)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
    (args.out / "index.html").write_text(page, encoding="utf-8")
    print(f"{len(order)} slides {w}x{h} -> {args.out / 'index.html'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
